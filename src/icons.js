export const ICON_NAMES = [...ALL.keys()];
export const hasIcon = (name) => ALL.has(name);

// an icon as a piece of SVG text (for places that write HTML)
export function iconSvg(name, size = 24) {
  const body = ALL.get(name) || ALL.get("mdi:square-small");
  return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

// <ra-icon icon="…">: sized by --mdc-icon-size like before, coloured by the text colour
if (typeof customElements !== "undefined" && !customElements.get("ra-icon")) {
  customElements.define("ra-icon", class extends HTMLElement {
    static get observedAttributes() { return ["icon"]; }
    connectedCallback() { this.draw(); }
    attributeChangedCallback() { this.draw(); }
    set icon(v) { this.setAttribute("icon", v); }
    get icon() { return this.getAttribute("icon"); }
    draw() {
      const n = this.getAttribute("icon") || ""; if (this._n === n) return; this._n = n;
      this.style.cssText ||= "display:inline-flex;align-items:center;justify-content:center;width:var(--mdc-icon-size,24px);height:var(--mdc-icon-size,24px);flex:none;line-height:0";
      // an icon a device brings from Home Assistant that the set has no drawing for: Home Assistant's own
      if (!ALL.has(n) && n.startsWith("mdi:") && customElements.get("ha-icon")) { this.innerHTML = `<ha-icon icon="${n.replace(/"/g, "")}" style="--mdc-icon-size:100%"></ha-icon>`; return; }
      this.innerHTML = iconSvg(n).replace('width="24" height="24"', 'width="100%" height="100%"');
    }
  });
}
